/** Las cajitas de leche (como la referencia): la tapa blanca, el techito, la carita de enfrente y su costado. */
function cajita(fr, frC, lado, ladoO, icono) {
  const t = (s) => s.replace(/%/g, fr).replace(/&/g, frC).replace(/\$/g, lado).replace(/\*/g, ladoO);
  return [
    "................",
    "....WWWWWWW.....",
    "....eeeeeeeE....",
    "...&&&&&&&&$$...",
    "...%%%%%%%%$$...",
    "...WWWWWWWW*$...",
    ...icono.map(t),
    "...%%%%%%%%*$...",
    "...&&&&&&&&**...",
    "................",
    "................",
  ].map(t);
}

