/** Revisa que todas las filas midan lo mismo (para dibujar sin errores). */
export function revisarComida() {
  const mal = [];
  const ver = (k, filas, w, h) => { if (filas.length !== h) mal.push(`${k}: ${filas.length} filas (debe ${h})`); filas.forEach((f, i) => { if (f.length !== w) mal.push(`${k}: fila ${i} mide ${f.length} (debe ${w})`); }); };
  for (const [k, f] of Object.entries(MANO)) ver(k, f, 16, 16);
  for (const [k, f] of Object.entries(PLATILLOS)) ver(k, f, 22, 15);
  return mal;
}
